"""Writes a training image list where cat images appear more than once, plus a dataset yaml that uses it.

Purpose: Ultralytics has no per-class loss weights, so the simplest way to make cats count more is to show
         each cat image more often per epoch (experiment E1c). Val and test are untouched, so scores stay
         comparable with E1.
Status:  Written; list logic tested (tests/test_analysis.py).
Later stages (still to add or change):
  - Phase 2b: our own trap footage can be repeated the same way (--extra-dir, repeated --extra-repeat times).

Training images stay where download_images.py put them; only a text file of paths is written. Both
outputs go in the data folder (not the repo) because they contain absolute PACE paths.

    python data/make_train_list.py --data ~/scratch/scout_data --cat-repeat 2
    # -> ~/scratch/scout_data/yolo/train_cat2x.txt and ~/scratch/scout_data/scout_cat2x.yaml
    python training/train_yolo.py --name E1c --data-yaml ~/scratch/scout_data/scout_cat2x.yaml
"""
from __future__ import annotations

import argparse
from pathlib import Path

from common import CLASS_ID, CLASSES

CAT = CLASS_ID["cat"]


def has_cat(label_file: Path) -> bool:
    if not label_file.exists():
        return False
    return any(line.split()[:1] == [str(CAT)] for line in label_file.read_text().splitlines())


def build_list(images: list[Path], labels_dir: Path, cat_repeat: int,
               extra: list[Path] = (), extra_repeat: int = 1) -> list[str]:
    out = []
    for p in images:
        out += [str(p)] * (cat_repeat if has_cat(labels_dir / f"{p.stem}.txt") else 1)
    for p in extra:
        out += [str(p)] * extra_repeat
    return out


def yaml_text(root: Path, train_list: str) -> str:
    names = "\n".join(f"  {i}: {n}" for i, n in enumerate(CLASSES))
    return (f"# Generated by data/make_train_list.py. Do not commit (absolute paths).\n"
            f"path: {root}\ntrain: {train_list}\nval: images/val\ntest: images/test\n\nnames:\n{names}\n")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", required=True)
    ap.add_argument("--cat-repeat", type=int, default=2)
    ap.add_argument("--extra-dir", help="extra image folder (e.g. our trap footage, labels in ../labels/...)")
    ap.add_argument("--extra-repeat", type=int, default=1)
    ap.add_argument("--tag", help="name suffix; default cat<N>x")
    args = ap.parse_args()

    data = Path(args.data).expanduser().resolve()
    root = data / "yolo"
    images = sorted((root / "images" / "train").glob("*.jpg"))
    extra = sorted(Path(args.extra_dir).expanduser().resolve().glob("*.jpg")) if args.extra_dir else []
    lines = build_list(images, root / "labels" / "train", args.cat_repeat, extra, args.extra_repeat)

    tag = args.tag or f"cat{args.cat_repeat}x"
    lst = root / f"train_{tag}.txt"
    lst.write_text("\n".join(lines) + "\n")
    yml = data / f"scout_{tag}.yaml"
    yml.write_text(yaml_text(root, lst.name))
    n_cat = sum(has_cat(root / "labels" / "train" / f"{p.stem}.txt") for p in images)
    print(f"{len(images):,} train images ({n_cat:,} with cats) -> {len(lines):,} list entries")
    print(f"wrote {lst}\nwrote {yml}")


if __name__ == "__main__":
    main()
